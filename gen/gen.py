#!/usr/bin/env python3
"""Emit a refutation certificate for (e1,e2) in base b as a Lean list of Ent.

Covers the crude band (lo, hi) with consecutive intervals [a, c), each tagged:
  0 lenBad   : n^e1, n^e2 have constant lengths L1+L2 != b on [a,c)
  1 topClash : top h digits of both powers constant on [a,c) and they repeat a value
  2 scan     : every n in [a,c) checked in full (lowSlots with the known lengths)
"""
import sys
def floor_root(x, e):
    lo, hi = 0, 1
    while hi ** e <= x: hi *= 2
    while lo < hi:
        m = (lo + hi + 1) // 2
        if m ** e <= x: lo = m
        else: hi = m - 1
    return lo
def ceil_root(x, e):
    r = floor_root(x, e)
    return r if r ** e == x else r + 1
def ndig(x, b):
    d = 0
    while x: x //= b; d += 1
    return d
def top(x, b, L, h):  # top h digits, least significant first (== topSlots)
    q = x // b ** (L - h)
    return [(q // b ** i) % b for i in range(h)]
def gen(b, e1, e2, scan_w):
    E = e1 + e2
    lo = ceil_root(b ** (b - 2), E) - 1          # lo^E < b^(b-2)
    hi = ceil_root(b ** b, E)                    # b^b <= hi^E
    assert lo ** E < b ** (b - 2) <= (lo + 1) ** E and b ** b <= hi ** E
    # length breakpoints
    cuts = {lo + 1, hi}
    for e in (e1, e2):
        for j in range(1, 3 * b):
            r = ceil_root(b ** j, e)
            if lo + 1 < r < hi: cuts.add(r)
    cuts = sorted(cuts)
    ents = []; stats = {0: 0, 1: 0, 2: 0, 'scanned': 0}
    def emit(a, c, tag, L1, L2, h):
        ents.append((a, c, tag, L1, L2, h)); stats[tag] += 1
        if tag == 2: stats['scanned'] += c - a
    def tree(a, c, L1, L2, free):
        # largest h with both top quotients constant on [a, c)
        h = 0
        while h < min(L1, L2):
            h2 = h + 1
            if (a ** e1) // b ** (L1 - h2) != ((c - 1) ** e1) // b ** (L1 - h2): break
            if (a ** e2) // b ** (L2 - h2) != ((c - 1) ** e2) // b ** (L2 - h2): break
            h = h2
        s = top(a ** e1, b, L1, h) + top(a ** e2, b, L2, h)
        if len(set(s)) < len(s):
            return emit(a, c, 1, L1, L2, h)
        if c - a <= scan_w or free == 0:
            return emit(a, c, 2, L1, L2, 0)
        B = b ** (free - 1); s0 = (a // B) * B
        while s0 < c:
            tree(max(s0, a), min(s0 + B, c), L1, L2, free - 1); s0 += B
    D = ndig(hi, b)
    for a, c in zip(cuts, cuts[1:]):
        L1, L2 = ndig(a ** e1, b), ndig(a ** e2, b)
        assert (L1, L2) == (ndig((c - 1) ** e1, b), ndig((c - 1) ** e2, b))
        if L1 + L2 != b: emit(a, c, 0, L1, L2, 0)
        else: tree(a, c, L1, L2, D)
    return lo, hi, ents, stats
PAIR_DIR = {(2, 3): "TwoThree"}

def module_name(b, e1, e2):
    return f"NiceCertified.{PAIR_DIR.get((e1, e2), f'Pair{e1}{e2}')}.Base{b}"

def theorem_name(b, e1, e2):
    return f"base_{b}_empty_{e1}_{e2}"

def lean_module(b, e1, e2, scan_w):
    lo, hi, ents, st = gen(b, e1, e2, scan_w)
    name = f"cert_{b}_{e1}_{e2}"
    body = ",\n  ".join(f"⟨{a}, {c}, {t}, {L1}, {L2}, {h}⟩" for a, c, t, L1, L2, h in ents)
    return st, f"""import NiceCertified.Checker

/-!
Generated by `gen/gen.py {b} {e1} {e2} {scan_w}`; do not edit by hand.

{len(ents)} intervals covering `({lo}, {hi})`: {st[0]} with the wrong digit lengths,
{st[1]} retired by a top-digit clash, {st[2]} scanned candidate by candidate
({st['scanned']} candidates).
-/

namespace Nice.Cert

def {name} : List Ent := [
  {body}]

set_option maxRecDepth 100000 in
theorem {name}_ok : checkChain {b} {e1} {e2} ({lo} + 1) {name} {hi} = true := by
  decide +kernel

/-- **No `({e1},{e2})`-nice number exists in base {b}.** -/
theorem {theorem_name(b, e1, e2)} (n : Nat) : ¬ Pandigital {b} {e1} {e2} n :=
  no_nice_of_cert (lo := {lo}) (hi := {hi}) (by decide) (by decide) (by decide)
    {name} {name}_ok n

end Nice.Cert
"""

if __name__ == "__main__":
    args = sys.argv[1:]
    b, e1, e2 = map(int, args[:3])
    w = int(args[3]) if len(args) > 3 else b
    st, text = lean_module(b, e1, e2, w)
    print(f"base {b} ({e1},{e2}): {st}", file=sys.stderr)
    sys.stdout.write(text)
